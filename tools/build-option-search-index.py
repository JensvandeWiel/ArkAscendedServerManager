#!/usr/bin/env python3
"""Build the global option-search index used by the server screen.

The UI is hand-written per tab, so there is no runtime metadata table to search.
This script scans the server tab sources for `Res.string.*_label` / `_hint`
references and emits a small Kotlin list with the owning tab.

Run from the repository root:

    python tools/build-option-search-index.py
"""

from __future__ import annotations

import argparse
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STRINGS = ROOT / "ui/src/main/composeResources/values/strings_servers.xml"
UI_SERVER = ROOT / "ui/src/main/kotlin/features/server"
OUT = UI_SERVER / "search/OptionSearchIndex.kt"

TAB_BY_FILE = {
    "InfoTabContent.kt": "INFO",
    "ProfileTabContent.kt": "PROFILE",
    "GeneralTabContent.kt": "GENERAL",
    "ManagementTabContent.kt": "MANAGEMENT",
    "EnvironmentTabContent.kt": "ENVIRONMENT",
    "RulesTabContent.kt": "RULES",
    "PlayerTabContent.kt": "PLAYER",
    "DinoSettingsTabContent.kt": "DINO_SETTINGS",
    "TablesTabContent.kt": "TABLES",
    "StructuresAndItemsTabContent.kt": "STRUCTURES_AND_ITEMS",
    "AdminAndSecurityTabContent.kt": "ADMIN_AND_SECURITY",
    "AdvancedAndLaunchTabContent.kt": "ADVANCED_AND_LAUNCH",
    "ChatAndHudTabContent.kt": "CHAT_AND_HUD",
    "ConfigEditorTabContent.kt": "CONFIG_EDITOR",
}
STRING_REF = re.compile(r"Res\.string\.([A-Za-z0-9_]+)")
LABEL_KEY = re.compile(r"^(.+)_label$")


def load_strings() -> dict[str, str]:
    root = ET.parse(STRINGS).getroot()
    result: dict[str, str] = {}
    for element in root.findall("string"):
        name = element.attrib.get("name")
        if name:
            result[name] = " ".join("".join(element.itertext()).split())
    return result


def tab_for(path: Path) -> str | None:
    if path.parent.name == "general":
        return "GENERAL"
    return TAB_BY_FILE.get(path.name)


def collect_entries(strings: dict[str, str]) -> list[tuple[str, str, str | None]]:
    entries: dict[tuple[str, str], tuple[str, str, str | None]] = {}
    for path in sorted(UI_SERVER.glob("*.kt")) + sorted((UI_SERVER / "general").glob("*.kt")):
        tab = tab_for(path)
        if tab is None:
            continue
        text = path.read_text(encoding="utf-8")
        for key in STRING_REF.findall(text):
            match = LABEL_KEY.match(key)
            if not match:
                continue
            label = strings.get(key)
            if not label:
                continue
            hint = strings.get(f"{match.group(1)}_hint")
            entries[(tab, label)] = (tab, label, hint)
    return sorted(entries.values(), key=lambda item: (item[0], item[1].lower()))


def kotlin_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def write_index(entries: list[tuple[str, str, str | None]]) -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "package eu.wynq.arkascendedservermanager.ui.features.server.search",
        "",
        "import eu.wynq.arkascendedservermanager.ui.features.server.ServerDetailsTab",
        "",
        "/** Generated by tools/build-option-search-index.py; do not edit by hand. */",
        "data class OptionSearchEntry(",
        "    val tab: ServerDetailsTab,",
        "    val label: String,",
        "    val hint: String? = null,",
        ")",
        "",
        "val optionSearchEntries: List<OptionSearchEntry> = listOf(",
    ]
    for tab, label, hint in entries:
        hint_value = "null" if hint is None else kotlin_string(hint)
        lines.append(
            f"    OptionSearchEntry(ServerDetailsTab.{tab}, {kotlin_string(label)}, {hint_value}),"
        )
    lines.append(")")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(entries)} entries)")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if the generated index is stale")
    args = parser.parse_args()
    strings = load_strings()
    entries = collect_entries(strings)
    if args.check:
        expected = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        # Regenerate into a temporary file for comparison without touching the tree.
        before = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        write_index(entries)
        after = OUT.read_text(encoding="utf-8")
        if before is not None and before != after:
            print("option-search index was stale; regenerated it")
            return 1
        return 0
    write_index(entries)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
